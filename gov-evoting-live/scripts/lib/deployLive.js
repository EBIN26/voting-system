// Deploys the election contract to a live network and records everything needed afterwards.
// Kept as a function (not just a script) so the same code can be rehearsed on a local chain
// and tested before it spends real (test) money.
const crypto = require("node:crypto");
const fs = require("node:fs");
const path = require("node:path");
const { explorer } = require("./live");

const HEX32 = /^0x[0-9a-fA-F]{64}$/;

function parseEnv(text) {
  const out = {};
  for (const line of text.split(/\r?\n/)) {
    const m = line.match(/^([A-Z0-9_]+)=(.*)$/);
    if (m) out[m[1]] = m[2];
  }
  return out;
}

/**
 * @param {object} o
 * @param {import("ethers").ContractFactory} o.factory  GovElection factory connected to the ADMIN signer
 * @param {object} o.wallets       contents of live/wallets.json
 * @param {string} o.keyHash       keccak256 of the election public key (from the key ceremony)
 * @param {string} o.title
 * @param {string[]} o.candidates
 * @param {number} o.threshold     trustees needed to agree (2)
 * @param {number} o.confirmations blocks to wait for before trusting the deployment
 * @param {string} o.rpcUrl        recorded for the later tools and the server
 * @param {string} o.liveDir
 * @param {(msg: string) => void} [o.log]
 */
async function deployLive({ factory, wallets, keyHash, title, candidates, threshold = 2, confirmations = 2, rpcUrl, liveDir, log = () => {} }) {
  const signer = factory.runner;
  const adminAddress = await signer.getAddress();
  if (adminAddress.toLowerCase() !== wallets.admin.address.toLowerCase()) {
    throw new Error(`The deploying account (${adminAddress}) is not the admin wallet in wallets.json (${wallets.admin.address}).`);
  }
  if (!HEX32.test(keyHash)) throw new Error("The election key hash is missing or malformed. Run the key ceremony first (node scripts/ceremony.js).");
  if (candidates.length < 2) throw new Error("An election needs at least 2 candidates.");

  const trusteeAddresses = wallets.trustees.map((t) => t.address);
  const args = [wallets.submitter.address, title, candidates, trusteeAddresses, threshold, keyHash];

  const provider = signer.provider;
  const network = await provider.getNetwork();
  const chainId = Number(network.chainId);

  // Check the admin can pay before sending anything.
  const tx = await factory.getDeployTransaction(...args);
  const [gas, fees, balance] = await Promise.all([provider.estimateGas({ ...tx, from: adminAddress }), provider.getFeeData(), provider.getBalance(adminAddress)]);
  const perGas = fees.maxFeePerGas ?? fees.gasPrice ?? 0n;
  const worstCase = (gas * perGas * 12n) / 10n;
  if (balance < worstCase) {
    const need = Number(worstCase) / 1e18;
    throw new Error(`The admin wallet ${adminAddress} has too little ETH to deploy (needs about ${need.toFixed(4)}). Get test ETH from a faucet.`);
  }

  log(`Deploying GovElection from ${adminAddress} on chain ${chainId}...`);
  const contract = await factory.deploy(...args);
  const deployTx = contract.deploymentTransaction();
  const receipt = await deployTx.wait(confirmations);
  const address = await contract.getAddress();

  // Read back what the chain holds, so the record is what is really deployed.
  const onChain = {
    admin: await contract.admin(), submitter: await contract.submitter(),
    threshold: Number(await contract.threshold()), keyHash: await contract.electionKeyHash(),
  };
  if (onChain.admin.toLowerCase() !== adminAddress.toLowerCase() || onChain.keyHash !== keyHash) {
    throw new Error("The deployed contract does not match what was requested. Do not use it.");
  }

  const record = {
    contract: address, chainId, deployBlock: receipt.blockNumber, txHash: deployTx.hash,
    rpcUrl, deployedAt: new Date().toISOString(), title, candidates,
    admin: adminAddress, submitter: wallets.submitter.address, trustees: trusteeAddresses,
    threshold, electionKeyHash: keyHash, explorer: explorer(chainId, address),
  };

  fs.mkdirSync(liveDir, { recursive: true });
  fs.writeFileSync(path.join(liveDir, "deployment.json"), JSON.stringify(record, null, 2));
  // Arguments for `hardhat verify`, so the source can be published on Etherscan.
  fs.writeFileSync(path.join(liveDir, "verify-args.js"), `module.exports = ${JSON.stringify(args, null, 2)};\n`);

  // The server's settings. A re-deploy keeps the secrets so the server's database stays valid.
  const envFile = path.join(liveDir, "server.env");
  const old = fs.existsSync(envFile) ? parseEnv(fs.readFileSync(envFile, "utf8")) : {};
  const rand = () => crypto.randomBytes(32).toString("hex");
  const lines = [
    "# Generated by scripts/deploy-live.js. Copy to the cloud server; never commit it.",
    "# It holds ONLY the submitter key. The admin and trustee keys never leave your computer.",
    `RPC_URL=${rpcUrl}`,
    `CONTRACT_ADDRESS=${address}`,
    `DEPLOY_BLOCK=${receipt.blockNumber}`,
    `SUBMITTER_PRIVATE_KEY=${wallets.submitter.privateKey}`,
    `ID_PEPPER=${old.ID_PEPPER || rand()}`,
    `OTP_SECRET=${old.OTP_SECRET || rand()}`,
    `ADMIN_API_KEY=${old.ADMIN_API_KEY || rand()}`,
    `MOCK_UIDAI_SECRET=${old.MOCK_UIDAI_SECRET || rand()}`,
    "",
    "# Server settings (a reverse proxy in front terminates HTTPS)",
    "HOST=0.0.0.0",
    "PORT=3000",
    "TRUST_PROXY=1",
    "DB_FILE=/data/evoting.sqlite",
    "MOCK_UIDAI_FILE=/data/mock-uidai.json",
    "ELECTION_PUBLIC_KEY_FILE=/app/ceremony/election-public-key.pem",
    "",
    "# DEMO ONLY: the one-click vote page and on-screen OTPs. Remove both lines for anything else.",
    "SIMPLE_VOTING=1",
    "SHOW_DEMO_OTP=1",
    "",
  ];
  fs.writeFileSync(envFile, lines.join("\n"), { mode: 0o600 });
  log(`Deployed at ${address} (block ${receipt.blockNumber}).`);
  return record;
}

module.exports = { deployLive, parseEnv };
